"""Arabizi (عربيزي) — Gradio version.

Pick a dialect, pick one of its Arabic words, write it in arabizi, and get a
funny verdict: match (one of the spellings people actually use) or no match.

The words live in the Hugging Face bucket VARabi/arabizi (see "Dictionary" below).

Run:  pip install -r requirements.txt   then   hf auth login   then   python app.py
"""
import base64
import csv
import os
import re
import tempfile

import gradio as gr
from huggingface_hub import sync_bucket

# ---------------------------------------------------------------- Dictionary
# The dictionary lives in a Hugging Face bucket, VARabi/arabizi by default (set ARABIZI_BUCKET to use
# another). The bucket is private, so reading it takes a token that can see it: a local `hf auth login`,
# or an HF_TOKEN secret on a Space. It is downloaded once at startup; restart the app to pick up changes.
# dialects.csv — one row per dialect: code, name, arabic. Row order is the flag-strip order, and the
#   dialect's flag is flags/<code>.png.
# words.csv — one row per spelling: dialect, word, arabic, arabizi. Rows sharing a dialect and word
#   number are one word. Words keep file order, and a word's first spelling is the one shown.
#   The surveyed dialects' rows are generated by build_words.py; the rest are hand-written.
# Both files are UTF-8 (with a BOM, so Excel keeps the Arabic). A bad file stops the app with
# the file and line at fault rather than loading half a dictionary.
BUCKET = os.environ.get("ARABIZI_BUCKET", "VARabi/arabizi")
ARABIC = re.compile(r"[؀-ۿ]")


def fetch_bucket(folder):
    """Download the bucket's files into folder."""
    try:
        sync_bucket(f"hf://buckets/{BUCKET}", folder, quiet=True)
    except Exception as e:
        raise SystemExit(f"Could not download the bucket {BUCKET} ({e}). "
                         "Log in with `hf auth login`, or set HF_TOKEN to a token that can read it.")
    for name in ("dialects.csv", "words.csv"):
        if not os.path.exists(os.path.join(folder, name)):
            raise SystemExit(f"The bucket {BUCKET} has no {name}")


def fail(path, line, msg):
    raise SystemExit(f"{os.path.basename(path)}, line {line}: {msg}")


def read_rows(folder, name, columns):
    """(line number, row dict) for each data row of a CSV in folder, after checking its header."""
    path = os.path.join(folder, name)
    try:
        with open(path, encoding="utf-8-sig", newline="") as f:
            reader = csv.DictReader(f)
            if reader.fieldnames != columns:
                fail(path, 1, f"expected the columns {', '.join(columns)}, found {', '.join(reader.fieldnames or [])}")
            rows = [(reader.line_num, {k: (v or "").strip() for k, v in r.items()}) for r in reader]
    except UnicodeDecodeError:
        raise SystemExit(f"{name} is not UTF-8. In Excel, save it as \"CSV UTF-8 (Comma delimited)\".")
    return path, rows


def load_dialects(folder):
    path, rows = read_rows(folder, "dialects.csv", ["code", "name", "arabic"])
    dialects = {}
    for line, r in rows:
        code = r["code"]
        if not code or not r["name"]:
            fail(path, line, "code and name are required")
        if code in dialects:
            fail(path, line, f'dialect "{code}" is listed twice')
        if not ARABIC.search(r["arabic"]):
            fail(path, line, f'"{r["arabic"]}" has no Arabic letters (was the file saved as plain CSV?)')
        if not os.path.exists(os.path.join(folder, "flags", f"{code}.png")):
            fail(path, line, f"no flag at flags/{code}.png")
        dialects[code] = {"name": r["name"], "ar": r["arabic"], "words": []}
    return dialects


def load_words(folder, dialects):
    path, rows = read_rows(folder, "words.csv", ["dialect", "word", "arabic", "arabizi"])
    words = {code: {} for code in dialects}  # code -> {word number: (arabic, [spellings])}, in file order
    for line, r in rows:
        code = r["dialect"]
        if code not in dialects:
            fail(path, line, f'unknown dialect "{code}" (add it to dialects.csv first)')
        if not r["word"].isdigit():
            fail(path, line, f'word must be a number, found "{r["word"]}"')
        if not ARABIC.search(r["arabic"]):
            fail(path, line, f'"{r["arabic"]}" has no Arabic letters (was the file saved as plain CSV?)')
        if not r["arabizi"]:
            fail(path, line, "arabizi is empty")
        arabic, spellings = words[code].setdefault(int(r["word"]), (r["arabic"], []))
        if arabic != r["arabic"]:
            fail(path, line, f'word {r["word"]} of "{code}" is "{arabic}" on earlier lines, not "{r["arabic"]}"')
        spellings.append(r["arabizi"])
    for code, d in dialects.items():
        if not words[code]:
            raise SystemExit(f'words.csv has no words for dialect "{code}"')
        d["words"] = [(spellings, arabic) for arabic, spellings in words[code].values()]
    return dialects


# Square PNG flags (rendered from the MIT-licensed flag-icons project), one per dialect: flags/<code>.png
def flag_data_uri(folder, code):
    with open(os.path.join(folder, "flags", f"{code}.png"), "rb") as f:
        return "data:image/png;base64," + base64.b64encode(f.read()).decode()


# Everything is read into memory here, so the downloaded files can go once loaded
with tempfile.TemporaryDirectory(prefix="arabizi-") as data:
    fetch_bucket(data)
    DIALECTS = load_words(data, load_dialects(data))
    FLAG_URI = {code: flag_data_uri(data, code) for code in DIALECTS}

# ---------------------------------------------------------------- Replies
# The same for every dialect; {w} is the user's spelling
HIT = 'Correct! "{w}" is how people write it.'
MISS = 'Not quite. "{w}" isn\'t a spelling we know for this word.'

# ---------------------------------------------------------------- Matching
def matches(code, idx, raw):
    """Full match only: raw must be one of the chosen word's listed spellings (case and outer spaces ignored)."""
    variants, _ = DIALECTS[code]["words"][idx]
    return raw.strip().casefold() in {v.casefold() for v in variants}


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


# ---------------------------------------------------------------- UI helpers
# Arabic name on the first line, English under it (the two are styled apart via ::first-line)
CHOICES = [(f'{d["ar"]}\n{d["name"]}', code) for code, d in DIALECTS.items()]
START = "tn"


def verdict(kind, body):
    return f'<div class="verdict {kind}">{body}</div>'


# No verdict yet: the result panel is hidden (see #result CSS)
IDLE = verdict("idle", "")


def word_choices(code):
    # The value is the word's position, so a repeated Arabic word (two TSV columns) stays two choices
    return [(ar, i) for i, (_, ar) in enumerate(DIALECTS[code]["words"])]


def placeholder(code, idx):
    if idx is None:
        return "Choose a word first"
    return f'Write "{DIALECTS[code]["words"][idx][1]}" in arabizi…'


# ---------------------------------------------------------------- Events
def choose(code):
    if not code:
        return gr.skip()
    return (gr.update(choices=word_choices(code), value=None), IDLE,
            gr.update(value="", placeholder=placeholder(code, None), interactive=False), gr.update(interactive=False))


def pick(idx, code):
    if not code:
        return gr.skip()
    ready = idx is not None
    return IDLE, gr.update(value="", placeholder=placeholder(code, idx), interactive=ready), gr.update(interactive=ready)


def check(raw, code, idx):
    raw = (raw or "").strip()
    if not code or idx is None:
        return gr.skip()
    if not raw:
        return IDLE
    w = esc(raw)
    variants, _ = DIALECTS[code]["words"][idx]
    if matches(code, idx, raw):
        return verdict("hit", HIT.format(w=w) +
                              f'<div class="meaning">Most people write it: {esc(variants[0])}</div>')
    return verdict("miss", MISS.format(w=w))


