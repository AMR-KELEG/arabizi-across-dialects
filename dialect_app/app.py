# ---------------------------------------------------------------- Matching
def matches(code, idx, raw):
    """Full match only: raw must be one of the chosen word's listed spellings (case and outer spaces ignored)."""
    variants, _ = DIALECTS[code]["words"][idx]
    return raw.strip().casefold() in {v.casefold() for v in variants}


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


# ---------------------------------------------------------------- Flags
# Square PNG flags (rendered from the MIT-licensed flag-icons project), one per dialect: flags/<code>.png
def flag_data_uri(code):
    with open(os.path.join(FLAG_DIR, f"{code}.png"), "rb") as f:
        return "data:image/png;base64," + base64.b64encode(f.read()).decode()


FLAG_URI = {code: flag_data_uri(code) for code in DIALECTS}

# ---------------------------------------------------------------- UI helpers
# Arabic name on the first line, English under it (the two are styled apart via ::first-line)
CHOICES = [(f'{d["ar"]}\n{d["name"]}', code) for code, d in DIALECTS.items()]
START = "tn"


def verdict(kind, body):
    return f'<div class="verdict {kind}">{body}</div>'


# No verdict yet: the result panel is hidden (see #result CSS)
IDLE = verdict("idle", "")


def word_choices(code):
    # The value is the word's position, so a repeated Arabic word (two TSV columns) stays two choices
    return [(ar, i) for i, (_, ar) in enumerate(DIALECTS[code]["words"])]


def placeholder(code, idx):
    if idx is None:
        return "Choose a word first"
    return f'Write "{DIALECTS[code]["words"][idx][1]}" in arabizi…'


# ---------------------------------------------------------------- Events
def choose(code):
    if not code:
        return gr.skip()
    return (gr.update(choices=word_choices(code), value=None), IDLE,
            gr.update(value="", placeholder=placeholder(code, None), interactive=False), gr.update(interactive=False))


def pick(idx, code):
    if not code:
        return gr.skip()
    ready = idx is not None
    return IDLE, gr.update(value="", placeholder=placeholder(code, idx), interactive=ready), gr.update(interactive=ready)


def check(raw, code, idx):
    raw = (raw or "").strip()
    if not code or idx is None:
        return gr.skip()
    if not raw:
        return IDLE
    w = esc(raw)
    variants, _ = DIALECTS[code]["words"][idx]
    if matches(code, idx, raw):
        return verdict("hit", f'{random.choice(HIT.get(code, DEFAULT_HIT)).format(w=w)}'
                              f'<div class="meaning">Most people write it: {esc(variants[0])}</div>')
    return verdict("miss", random.choice(MISS.get(code, DEFAULT_MISS)).format(w=w))


