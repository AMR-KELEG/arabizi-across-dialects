# ---------------------------------------------------------------- Dictionary
# The dictionary lives in a Hugging Face bucket, VARabi/VARabiziLex-bucket by default (set ARABIZI_BUCKET to use
# another). The bucket is private, so reading it takes a token that can see it: a local `hf auth login`,
# or an HF_TOKEN secret on a Space. It is downloaded once at startup; restart the app to pick up changes.
# dialects.csv — one row per dialect: code, name, arabic. Row order is the flag-strip order, and the
#   dialect's flag is flags/<code>.png.
# words.csv — one row per spelling: dialect, word, arabic, arabizi. Rows sharing a dialect and word
#   number are one word. Words keep file order, and a word's first spelling is the one shown.
#   The surveyed dialects' rows are generated by build_words.py; the rest are hand-written.
# Both files are UTF-8 (with a BOM, so Excel keeps the Arabic). A bad file stops the app with
# the file and line at fault rather than loading half a dictionary.
# submissions/<code>/<time>-<visit id>.json — every spelling one visit to the page wrote for one dialect,
#   matching or not (see "Submissions" below), named by the time of the first:
#   {"visit", "dialect", "spellings": [{"word", "arabic", "arabizi", "known", "time"}, ...]}, where known
#   says whether the spelling was already one of the word's spellings when it was written. At startup a spelling
#   submitted at least MIN_SUBMISSIONS times for a word is added to that word's spellings. These files come
#   from users, so a bad file or entry is skipped with a warning instead of stopping the app. Saving them
#   takes a token that can write.
BUCKET = os.environ.get("ARABIZI_BUCKET", "VARabi/VARabiziLex-bucket")
HERE = os.path.dirname(os.path.abspath(__file__))
FLAG_DIR = os.path.join(HERE, "flags")
ARABIC = re.compile(r"[؀-ۿ]")
# What a user may type, and so what can be saved: the characters words.csv uses. Latin letters (accented
# ones too), digits, spaces, apostrophes (straight or curly) and hyphens, with at least one letter or digit
SPELLING = re.compile(r"(?=.*[A-Za-z0-9À-ÖØ-öø-ÿ])[A-Za-z0-9À-ÖØ-öø-ÿ '’-]+")
MAX_SPELLING = 40
MIN_SUBMISSIONS = 1
disable_progress_bars()  # each upload would otherwise draw progress bars in the app's log


def fetch_bucket(folder):
    """Download the bucket's files into folder."""
    try:
        sync_bucket(f"hf://buckets/{BUCKET}", folder, quiet=True)
    except Exception as e:
        raise SystemExit(f"Could not download the bucket {BUCKET} ({e}). "
                         "Log in with `hf auth login`, or set HF_TOKEN to a token that can read it.")
    for name in ("dialects.csv", "words.csv"):
        if not os.path.exists(os.path.join(folder, name)):
            raise SystemExit(f"The bucket {BUCKET} has no {name}")


def fail(path, line, msg):
    raise SystemExit(f"{os.path.basename(path)}, line {line}: {msg}")


def read_rows(folder, name, columns):
    """(line number, row dict) for each data row of a CSV in folder, after checking its header."""
    path = os.path.join(folder, name)
    try:
        with open(path, encoding="utf-8-sig", newline="") as f:
            reader = csv.DictReader(f)
            if reader.fieldnames != columns:
                fail(path, 1, f"expected the columns {', '.join(columns)}, found {', '.join(reader.fieldnames or [])}")
            rows = [(reader.line_num, {k: (v or "").strip() for k, v in r.items()}) for r in reader]
    except UnicodeDecodeError:
        raise SystemExit(f"{name} is not UTF-8. In Excel, save it as \"CSV UTF-8 (Comma delimited)\".")
    return path, rows


def load_dialects(folder):
    path, rows = read_rows(folder, "dialects.csv", ["code", "name", "arabic"])
    dialects = {}
    for line, r in rows:
        code = r["code"]
        if not code or not r["name"]:
            fail(path, line, "code and name are required")
        if code in dialects:
            fail(path, line, f'dialect "{code}" is listed twice')
        if not ARABIC.search(r["arabic"]):
            fail(path, line, f'"{r["arabic"]}" has no Arabic letters (was the file saved as plain CSV?)')
        if not os.path.exists(os.path.join(folder, "flags", f"{code}.png")):
            fail(path, line, f"no flag at flags/{code}.png")
        dialects[code] = {"name": r["name"], "ar": r["arabic"], "words": []}
    return dialects


def load_words(folder, dialects):
    path, rows = read_rows(folder, "words.csv", ["dialect", "word", "arabic", "arabizi"])
    words = {code: {} for code in dialects}  # code -> {word number: (arabic, [spellings])}, in file order
    for line, r in rows:
        code = r["dialect"]
        if code not in dialects:
            fail(path, line, f'unknown dialect "{code}" (add it to dialects.csv first)')
        if not r["word"].isdigit():
            fail(path, line, f'word must be a number, found "{r["word"]}"')
        if not ARABIC.search(r["arabic"]):
            fail(path, line, f'"{r["arabic"]}" has no Arabic letters (was the file saved as plain CSV?)')
        if not r["arabizi"]:
            fail(path, line, "arabizi is empty")
        arabic, spellings = words[code].setdefault(int(r["word"]), (r["arabic"], []))
        if arabic != r["arabic"]:
            fail(path, line, f'word {r["word"]} of "{code}" is "{arabic}" on earlier lines, not "{r["arabic"]}"')
        spellings.append(r["arabizi"])
    load_submissions(folder, words)
    for code, d in dialects.items():
        if not words[code]:
            raise SystemExit(f'words.csv has no words for dialect "{code}"')
        d["words"] = [(spellings, arabic) for arabic, spellings in words[code].values()]
        d["numbers"] = list(words[code])  # each word's number in words.csv, by position
    return dialects


def savable(spelling):
    return len(spelling) <= MAX_SPELLING and SPELLING.fullmatch(spelling) is not None


def load_submissions(folder, words):
    """Add each spelling submitted at least MIN_SUBMISSIONS times to its word's spellings, after the listed ones."""
    counts = collections.Counter()
    first = {}  # the spelling as first submitted, case and all
    # File names start with the time, so this is submission order
    for path in sorted(glob.glob(os.path.join(folder, "submissions", "*", "*.json"))):
        name = os.path.relpath(path, folder)
        try:
            with open(path, encoding="utf-8") as f:
                s = json.load(f)
            code, entries = s["dialect"], list(s["spellings"])
        except (OSError, ValueError, KeyError, TypeError) as e:
            print(f"Skipping {name}: {e!r}")
            continue
        for i, e in enumerate(entries):
            try:
                number, arabic, spelling = int(e["word"]), e["arabic"], e["arabizi"].strip()
            except (ValueError, KeyError, TypeError, AttributeError) as err:
                print(f"Skipping {name}, spelling {i + 1}: {err!r}")
                continue
            # A word renumbered or removed from words.csv since the submission no longer has the same Arabic
            if words.get(code, {}).get(number, (None,))[0] != arabic or not savable(spelling):
                print(f"Skipping {name}, spelling {i + 1}: it doesn't fit a word in words.csv")
                continue
            key = (code, number, spelling.casefold())
            counts[key] += 1
            first.setdefault(key, spelling)
    for (code, number, folded), n in counts.items():
        spellings = words[code][number][1]
        if n >= MIN_SUBMISSIONS and folded not in {v.casefold() for v in spellings}:
            spellings.append(first[code, number, folded])


# Square PNG flags (rendered from the MIT-licensed flag-icons project), one per dialect: flags/<code>.png
def flag_data_uri(folder, code):
    with open(os.path.join(folder, "flags", f"{code}.png"), "rb") as f:
        return "data:image/png;base64," + base64.b64encode(f.read()).decode()


# Everything is read into memory here, so the downloaded files can go once loaded
with tempfile.TemporaryDirectory(prefix="arabizi-") as data:
    fetch_bucket(data)
    DIALECTS = load_words(data, load_dialects(data))
    FLAG_URI = {code: flag_data_uri(data, code) for code in DIALECTS}

# ---------------------------------------------------------------- Replies
# The same for every dialect; {w} is the user's spelling
HIT = 'Correct! "{w}" is how people write it.'
MISS = 'Not quite. "{w}" isn\'t a spelling we know for this word.'
MISS_SAVED = 'Not quite. "{w}" isn\'t a spelling we know for this word yet. Thanks, we\'ve added it to our list.'
INVALID = 'Please use Latin letters and numbers only.'


# ---------------------------------------------------------------- Submissions
# Each visit keeps its own files in a gr.State: {"id", "files": {code: {"path", "record"}}}. A new spelling is
# added to the record and the whole file uploaded again, replacing the last upload.
UPLOAD_LOCK = threading.Lock()


def save_submission(visit, code, idx, spelling, known):
    """Add a spelling to this visit's file for the dialect, and save that to the bucket.
    Returns the visit's state. The upload runs in the background so the reply doesn't wait for it; if it
    fails, the app logs it and carries on."""
    now = datetime.now(timezone.utc)
    visit = visit or {"id": uuid.uuid4().hex[:8], "files": {}}
    file = visit["files"].setdefault(code, {
        "path": f"submissions/{code}/{now:%Y%m%dT%H%M%S}-{visit['id']}.json",
        "record": {"visit": visit["id"], "dialect": code, "spellings": []}})
    file["record"]["spellings"].append({"word": DIALECTS[code]["numbers"][idx], "arabic": DIALECTS[code]["words"][idx][1],
                                        "arabizi": spelling, "known": known, "time": now.isoformat(timespec="seconds")})

    def upload():
        # One upload at a time, each sending the record as it is then: two quick checks can't leave the
        # earlier, shorter version of a file as the last one saved
        with UPLOAD_LOCK:
            try:
                batch_bucket_files(BUCKET, add=[(json.dumps(file["record"], ensure_ascii=False).encode(), file["path"])])
            except Exception as e:
                print(f"Could not save {file['path']} to the bucket {BUCKET}: {e!r}")

    threading.Thread(target=upload, daemon=True).start()
    return visit


# ---------------------------------------------------------------- Matching
def matches(code, idx, raw):
    """Full match only: raw must be one of the chosen word's listed spellings (case and outer spaces ignored)."""
    variants, _ = DIALECTS[code]["words"][idx]
    return raw.strip().casefold() in {v.casefold() for v in variants}


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


# ---------------------------------------------------------------- UI helpers
# The dialects of the survey dataset lead the flag strip, with a line between them and the rest (see Styles)
DATASET = ("tn", "ma", "dz", "eg", "lb")
# Arabic name on the first line, English under it (the two are styled apart via ::first-line)
CHOICES = [(f'{DIALECTS[code]["ar"]}\n{DIALECTS[code]["name"]}', code)
           for code in sorted(DIALECTS, key=lambda code: code not in DATASET)]
START = "tn"


def verdict(kind, body):
    return f'<div class="verdict {kind}">{body}</div>'


# No verdict yet: the result panel is hidden (see #result CSS)
IDLE = verdict("idle", "")


def word_choices(code):
    # The value is the word's position, so a repeated Arabic word (two TSV columns) stays two choices
    return [(ar, i) for i, (_, ar) in enumerate(DIALECTS[code]["words"])]


def placeholder(code, idx):
    if idx is None:
        return "Choose a word first"
    return f'Write "{DIALECTS[code]["words"][idx][1]}" in Arabizi (Franco)…'


# ---------------------------------------------------------------- Events
def choose(code):
    if not code:
        return gr.skip()
    return (gr.update(choices=word_choices(code), value=None), IDLE,
            gr.update(value="", placeholder=placeholder(code, None), interactive=False), gr.update(interactive=False))


def pick(idx, code):
    if not code:
        return gr.skip()
    ready = idx is not None
    return IDLE, gr.update(value="", placeholder=placeholder(code, idx), interactive=ready), gr.update(interactive=ready)


def check(raw, code, idx, visit):
    raw = (raw or "").strip()
    if not code or idx is None:
        return gr.skip()
    if not raw:
        return IDLE, visit
    if not SPELLING.fullmatch(raw):
        return verdict("invalid", INVALID), visit
    w = esc(raw)
    variants, _ = DIALECTS[code]["words"][idx]
    known = matches(code, idx, raw)
    if savable(raw):
        visit = save_submission(visit, code, idx, raw, known)
    if known:
        return verdict("hit", HIT.format(w=w) +
                              f'<div class="meaning">Most people write it: {esc(variants[0])}</div>'), visit
    return verdict("miss", (MISS_SAVED if savable(raw) else MISS).format(w=w)), visit


